const SOURCES_LABEL: Record<HadakLang, string> = { fr: 'Sources', da: 'L-masadir', en: 'Sources', ar: 'المصادر', es: 'Fuentes' };

export function describeProvenance(p: HadakProvenance, lang: HadakLang = 'fr'): { badge: string; why: string } {
  const colon = lang === 'fr' ? ' : ' : ': ';
  const sources = p.sources.length ? ` ${SOURCES_LABEL[lang]}${colon}${p.sources.join(', ')}.` : '';
  return { badge: BADGE[p.basis][lang], why: `${WHY[p.basis][lang]}${sources}` };
}

