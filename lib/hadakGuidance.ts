/**
 * Trust Layer + "Et maintenant ?" for Hadak answers. Pure: says where an
 * answer comes from and proposes at most three in-app sections to open next.
 * Nothing here runs an action; every action is INFORMATIONAL (opening a page
 * section changes nothing).
 */
import type { NextAction } from '@/lib/rmeMoments';
import type { TruthLevel } from '@/lib/trust';

export type HadakLang = 'fr' | 'da' | 'en' | 'ar' | 'es';

/**
 * CLOCK: server clock. LIVE_DATA: every fact read from a live source.
 * RME_GUIDE: written RME guidance (possibly with some live figures), not
 * verified with an authority. AI: generated by a language model.
 */
export type ProvenanceBasis = 'CLOCK' | 'LIVE_DATA' | 'RME_GUIDE' | 'AI';

export type HadakProvenance = {
  level: TruthLevel;
  basis: ProvenanceBasis;
  /** Live sources actually read for this answer (e.g. "Open-Meteo"). */
  sources: string[];
};

/** What the route observed while building one answer. */
export type AnswerTrace = {
  /** Live sources that returned data. */
  live: string[];
  /** True when every fact in the answer came from `live` or the clock. */
  liveOnly: boolean;
  clock?: boolean;
  ai?: boolean;
};

export function newTrace(): AnswerTrace {
  return { live: [], liveOnly: false };
}

export function provenanceOf(trace: AnswerTrace): HadakProvenance {
  const sources = [...new Set(trace.live)];
  if (trace.ai) return { level: 'INFERRED', basis: 'AI', sources };
  if (trace.clock) return { level: 'MEASURED', basis: 'CLOCK', sources };
  if (trace.liveOnly && sources.length > 0) return { level: 'MEASURED', basis: 'LIVE_DATA', sources };
  return { level: 'INFERRED', basis: 'RME_GUIDE', sources };
}

